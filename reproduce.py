"""Reproduce every number in results/results.md.

    python reproduce.py            # full run, a few minutes, pure Python

Two pendulums are released from rest. Blue starts at (start, start); red at
(start + difference, start): only the first arm differs. "Apart" means one
radian apart in angle space. Time is in swings, T0 = 2*pi*sqrt(l/g).
"""
import math
import sys
import time
from pathlib import Path

from pendulum.model import DEFAULT_STEP, SITE_EULER_STEP, euler, rk4
from pendulum.runs import record

OUT = Path(__file__).parent / "results" / "results.md"
H = DEFAULT_STEP


def fmt(x, nd=1):
    return "—" if x is None else f"{x:.{nd}f}"


def main():
    t0 = time.time()
    lines = ["# Results", "",
             "Generated by `reproduce.py`. Do not edit by hand.", "",
             "Blue released from rest at θ₁ = θ₂ = *start*; red at θ₁ = *start* + *difference*, "
             "θ₂ = *start*. **Swings** = T₀ = 2π√(l/g). **Apart** = one radian apart in angle space. "
             "Energy error: largest change in total energy over the run, as a fraction of the "
             "pendulum's potential-energy depth. RK4 step h = "
             f"{H} √(l/g); the convergence columns repeat the run at h/2.", ""]

    # 1. Which starting angles diverge?
    lines += ["## 1. Divergence by starting angle (difference 10⁻⁶°, up to 100 swings)", "",
              "| Model | Start | Swings until apart | at h/2 | Largest gap in 100 swings (rad) | Energy error |",
              "|---|---|---|---|---|---|"]
    for model in ("masses", "rods"):
        for start in (60, 90, 120, 150):
            s, g, dE = record(model, start, step=H)
            s2 = record(model, start, step=H / 2)[0] if start in (60, 120) else None
            half = fmt(s2) if s2 else ("not apart" if start in (60, 120) else "not run")
            gap_txt = f"{g:.1e}" if s is None else "≥ 1"
            lines.append(f"| {model} | {start}°/{start}° | {fmt(s) if s else 'not apart'} | "
                         f"{half} | {gap_txt} | {dE:.0e} |")
            print(lines[-1], flush=True)
    lines.append("")

    # 2. How much does precision buy?
    lines += ["## 2. Precision buys little time (swings until apart)", "",
              "| Model | Start | 10⁻³° | 10⁻⁶° | 10⁻⁹° | 10⁻¹²° |", "|---|---|---|---|---|---|"]
    for model in ("masses", "rods"):
        for start in (120, 150):
            row = [record(model, start, d, step=H)[0] for d in (1e-3, 1e-6, 1e-9, 1e-12)]
            lines.append(f"| {model} | {start}°/{start}° | " + " | ".join(fmt(x) for x in row) + " |")
            print(lines[-1], flush=True)
    lines += ["", "Each thousandfold gain in starting precision adds only a few swings: the time "
              "to divergence grows with the logarithm of the precision.", ""]

    # 3. The visualize-it simulation's method
    lines += ["## 3. The method used by visualize-it.github.io/double_pendulum", "",
              "That page uses the rods model in Hamiltonian form (`rods-site`) and forward Euler with a step of 0.1 in its own units "
              f"({SITE_EULER_STEP:.4f} √(l/g) on a 1366 px screen). Same start, 60°/60°, difference 10⁻⁶°:", "",
              "| Method | Swings until apart | Energy error |", "|---|---|---|"]
    for name, meth, h in (("RK4 (accurate)", rk4, H), ("forward Euler, as the site", euler, SITE_EULER_STEP)):
        s, g, dE = record("rods-site", 60, step=h, method=meth, max_swings=30)
        lines.append(f"| {name} | {fmt(s) if s else 'not apart in 30'} | {dE:.0e} |")
        print(lines[-1], flush=True)
    lines += ["", "Forward Euler adds energy at every step. From 60°/60° the real pendulum is regular; "
              "the site's pendulums gain energy until their arms go over the top, and only then diverge.", ""]

    # 4. The energy bar at 60/60
    lines += ["## 4. Why 60°/60° cannot go over the top", "",
              "Released from rest, the second arm can reach the top (θ₂ = 180°) only if the energy "
              "allows it. For the rods the condition is 3 cos θ₁ + cos θ₂ < 2; for the point masses, "
              "2 cos θ₁ + cos θ₂ < 1. At 60°/60° the rods sit exactly on the bar (3·½ + ½ = 2) and the "
              "masses fall short of it (2·½ + ½ = 1.5 > 1): neither can flip.", ""]

    lines.append(f"_Run time {time.time() - t0:.0f} s, Python {sys.version.split()[0]}._")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
